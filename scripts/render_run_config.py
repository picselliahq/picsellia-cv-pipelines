#!/usr/bin/env python3
"""Render a test run_config.toml by resolving its `@placeholders` to Picsellia_CI ids.

The run_configs under `tests/` no longer contain hard-coded UUIDs. They hold
placeholders that are resolved here from `tests/fixtures.lock.toml` (generated by
`scripts/provision_ci_org.py`) using the fixture name (the path of the test
folder under `tests/`, e.g. `yolov8/pre_annotation`):

    "@dataset_version"  -> fixtures.<name>.dataset_version_id
    "@model_version"    -> fixtures.<name>.model_version_id
    "@datalake"         -> org.datalake_id

The organization is not set here: `pxl-pipeline test` takes it from the login
context (`pxl-pipeline login --organization ...`, see scripts/test_pipelines.sh).

Exit codes: 0 rendered, 3 fixture intentionally not tested (on hold or not
provisioned yet; the reason is printed), 1 error (unresolved placeholder, ...).

Usage:
    python3 scripts/render_run_config.py --fixture yolov8/pre_annotation \
        --config tests/yolov8/pre_annotation/run_config.toml --out /tmp/run_config.toml
"""

from __future__ import annotations

import argparse
import re
import sys
import tomllib
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
PLACEHOLDERS = {
    "@dataset_version": ("fixture", "dataset_version_id"),
    "@model_version": ("fixture", "model_version_id"),
    "@datalake": ("org", "datalake_id"),
}
PLACEHOLDER_RE = re.compile(r'"(@[A-Za-z_]+)"')
SKIP = 3


def render(text: str, fixture: str, lock: dict) -> str:
    entry = lock.get("fixtures", {}).get(fixture, {})

    def resolve(match: re.Match) -> str:
        token = match.group(1)
        if token not in PLACEHOLDERS:
            raise ValueError(f"unknown placeholder {token}")
        scope, key = PLACEHOLDERS[token]
        value = (entry if scope == "fixture" else lock.get("org", {})).get(key)
        if not value:
            raise ValueError(f"{token}: '{key}' is missing in the lock for {fixture!r}")
        return f'"{value}"'

    return PLACEHOLDER_RE.sub(resolve, text)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--fixture", required=True, help="fixture name, e.g. yolov8/pre_annotation")
    ap.add_argument("--config", type=Path, required=True)
    ap.add_argument("--out", type=Path, required=True)
    ap.add_argument("--manifest", type=Path, default=REPO / "tests/fixtures.toml")
    ap.add_argument("--lock", type=Path, default=REPO / "tests/fixtures.lock.toml")
    args = ap.parse_args()

    manifest = tomllib.loads(args.manifest.read_text())
    if args.fixture in manifest.get("skipped", {}):
        print(f"skipped: {manifest['skipped'][args.fixture]['reason']}")
        return SKIP
    if args.fixture not in manifest.get("fixtures", {}):
        print(f"error: '{args.fixture}' is not declared in {args.manifest.name}", file=sys.stderr)
        return 1
    if not args.lock.exists():
        print(f"error: {args.lock} not found; run scripts/provision_ci_org.py --apply", file=sys.stderr)
        return 1
    lock = tomllib.loads(args.lock.read_text())
    if args.fixture not in lock.get("fixtures", {}):
        todo = manifest["fixtures"][args.fixture].get("todo", "not provisioned yet")
        print(f"skipped: not provisioned in Picsellia_CI ({todo})")
        return SKIP

    try:
        rendered = render(args.config.read_text(), args.fixture, lock)
        tomllib.loads(rendered)  # the result must stay valid TOML
    except (ValueError, tomllib.TOMLDecodeError) as e:
        print(f"error: {e}", file=sys.stderr)
        return 1
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(rendered)
    return 0


if __name__ == "__main__":
    sys.exit(main())
