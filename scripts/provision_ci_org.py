#!/usr/bin/env python3
"""Provision the CI fixtures of the `Picsellia_CI` staging organization.

Reads `tests/fixtures.toml` and, for every fixture:
  * copies a small subset (max `max_images` images, or `--max-videos` videos) of
    a source dataset version from the prod org (read only) into a dataset
    `ci-<pipeline>` / version `fixture-v1` of the CI org, with its annotations;
  * copies the base model weights from the org where they were uploaded by hand
    (`test-account`, read only) into a model `ci-<model>` of the CI org;
  * writes `tests/fixtures.lock.toml` (name -> ids) used by the run_configs.

Safety:
  * DRY-RUN by default: only read calls are made, nothing is created. Writing
    requires `--apply` (and a typed confirmation unless `--yes`).
  * Only the CI client ever writes; the two source clients are only read.
  * Idempotent: existing datasets/versions/models/files are reused, a version
    that already holds assets is not uploaded again.
  * Fixtures flagged with `todo` in the manifest are skipped unless
    `--include-todo` is given.
  * Output datasets (`ci-out-*`) are not created here: the pipelines create them.

Tokens are read from the environment (never from arguments):
  PXL_API_TOKEN_PROD     prod token, to read the source org (app.picsellia.com)
  PXL_API_TOKEN_STAGING  staging token, to read the base-models org and write the CI org

Usage:
  uv run python scripts/provision_ci_org.py                      # dry-run, all
  uv run python scripts/provision_ci_org.py --only 'yolov8/*'    # dry-run, subset
  uv run python scripts/provision_ci_org.py --apply              # really create
"""

from __future__ import annotations

import argparse
import fnmatch
import json
import os
import re
import shutil
import sys
import tempfile
import tomllib
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
UUID_RE = re.compile(r"^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$")
KINDS = {"detection", "segmentation", "classification", "video", "obb"}
REQUIRED = ("dataset", "kind", "output_name", "source_dataset", "source_version_id", "source_size")
MODEL_KEYS = ("model", "model_version", "model_source_version_id")
DATA_TAG = "ci-fixture"


# --------------------------------------------------------------------------- manifest
def load_manifest(path: Path) -> dict:
    manifest = tomllib.loads(path.read_text())
    errors: list[str] = []
    org = manifest.get("org", {})
    for key in ("name", "host", "source_org", "source_host", "base_models_source_org", "max_images", "dataset_version_name"):
        if key not in org:
            errors.append(f"[org] is missing '{key}'")
    seen: set[str] = set()
    for key, fx in manifest.get("fixtures", {}).items():
        for field in REQUIRED:
            if field not in fx:
                errors.append(f"{key}: missing '{field}'")
        if fx.get("kind") not in KINDS:
            errors.append(f"{key}: unknown kind {fx.get('kind')!r}")
        if not UUID_RE.match(str(fx.get("source_version_id", ""))):
            errors.append(f"{key}: source_version_id is not a UUID")
        given = [m in fx for m in MODEL_KEYS]
        if any(given) and not all(given):
            errors.append(f"{key}: model, model_version and model_source_version_id go together")
        if "model_source_version_id" in fx and not UUID_RE.match(fx["model_source_version_id"]):
            errors.append(f"{key}: model_source_version_id is not a UUID")
        if fx.get("dataset") in seen:
            errors.append(f"{key}: duplicate dataset name {fx['dataset']}")
        seen.add(fx.get("dataset", ""))
    if errors:
        raise SystemExit("invalid manifest:\n  " + "\n  ".join(errors))
    return manifest


def load_lock(path: Path) -> dict:
    data = tomllib.loads(path.read_text()) if path.exists() else {}
    return {"org": data.get("org", {}), "fixtures": data.get("fixtures", {})}


def write_lock(path: Path, lock: dict) -> None:
    lines = [
        "# GENERATED by scripts/provision_ci_org.py - do not edit by hand.",
        "# [org]: ids shared by every fixture; [fixtures.*]: fixture name -> ids in the Picsellia_CI organization.",
        "# Consumed by scripts/render_run_config.py.",
        "",
        "[org]",
        *[f"{k} = {json.dumps(v)}" for k, v in sorted(lock["org"].items())],
        "",
    ]
    for key in sorted(lock["fixtures"]):
        lines.append(f"[fixtures.{json.dumps(key)}]")
        lines += [f"{k} = {json.dumps(v)}" for k, v in sorted(lock["fixtures"][key].items())]
        lines.append("")
    path.write_text("\n".join(lines))


# --------------------------------------------------------------------------- helpers
def log(msg: str) -> None:
    print(msg, flush=True)


def get_or_none(fn, *args, **kwargs):
    from picsellia.exceptions import ResourceNotFoundError

    try:
        return fn(*args, **kwargs)
    except ResourceNotFoundError:
        return None


def find_source_version(client, cache: dict, dataset_name: str, version_id: str):
    if dataset_name not in cache:
        cache[dataset_name] = get_or_none(client.get_dataset, dataset_name)
    ds = cache[dataset_name]
    if ds is None:
        return None
    return next((v for v in ds.list_versions() if str(v.id) == version_id), None)


def find_model_version(client, cache: dict, version_id: str):
    if not cache:
        for model in client.list_models():
            for mv in model.list_versions():
                cache[str(mv.id)] = (model, mv)
    return cache.get(version_id)


# --------------------------------------------------------------------------- dataset
def provision_dataset(fx: dict, org: dict, clients: dict, caches: dict, apply: bool, max_videos: int, work: Path) -> dict:
    ids: dict[str, str] = {}
    src = find_source_version(clients["source"], caches["datasets"], fx["source_dataset"], fx["source_version_id"])
    if src is None:
        raise RuntimeError(f"source version {fx['source_version_id']} not found in dataset '{fx['source_dataset']}'")
    limit = max_videos if fx["kind"] == "video" else org["max_images"]
    n = min(limit, fx["source_size"])
    log(f"    source : {fx['source_dataset']} / {src.version} ({fx['source_size']} assets) -> copy {n}")

    target = clients["ci"]
    ds = get_or_none(target.get_dataset, fx["dataset"])
    dv = get_or_none(ds.get_version, org["dataset_version_name"]) if ds else None
    already = len(dv.list_assets(limit=1)) if dv else 0
    log(f"    target : dataset {'exists' if ds else 'to create'}, version {'exists' if dv else 'to create'}, "
        f"{'already filled' if already else 'empty'}")
    if dv:
        ids = {"dataset_id": str(ds.id), "dataset_version_id": str(dv.id)}
    if not apply or already:
        return ids

    from picsellia.types.enums import AnnotationFileType

    ds = ds or target.create_dataset(fx["dataset"], description=f"CI fixture for {fx['source_dataset']} (generated)")
    dv = dv or ds.create_version(org["dataset_version_name"], description="CI fixture (generated)", type=src.type)
    assets = src.list_assets(limit=limit)
    files_dir, ann_dir = work / "files", work / "ann"
    files_dir.mkdir(parents=True, exist_ok=True)
    ann_dir.mkdir(parents=True, exist_ok=True)
    assets.download(str(files_dir))
    paths = [files_dir / a.filename for a in assets if (files_dir / a.filename).exists()]
    if not paths:
        raise RuntimeError("no asset could be downloaded")
    data = target.get_datalake(name=org["datalake"]).upload_data(filepaths=paths, tags=[DATA_TAG])
    dv.add_data(data)
    log(f"    uploaded {len(paths)} files into {fx['dataset']} / {org['dataset_version_name']}")

    if fx["kind"] == "video":
        log("    annotations: skipped for videos")
    else:
        try:
            ann_file = src.export_annotation_file(AnnotationFileType.COCO, target_path=str(ann_dir), assets=assets)
            result = dv.import_annotations_coco_file(ann_file, force_create_label=True, fail_on_asset_not_found=False)
            log(f"    annotations imported: {result}")
        except Exception as e:  # noqa: BLE001 - keep the dataset, report it
            log(f"    WARNING annotations not imported ({type(e).__name__}: {e})")
    return {"dataset_id": str(ds.id), "dataset_version_id": str(dv.id)}


# --------------------------------------------------------------------------- model
def provision_model(fx: dict, clients: dict, caches: dict, apply: bool, work: Path) -> dict:
    found = find_model_version(clients["models_source"], caches["models"], fx["model_source_version_id"])
    if found is None:
        raise RuntimeError(f"source model version {fx['model_source_version_id']} not found")
    src_model, src_mv = found
    src_files = src_mv.list_files()
    log(f"    model  : {src_model.name}/{src_mv.name} -> {fx['model']}/{fx['model_version']} ({len(src_files)} files)")

    target = clients["ci"]
    model = get_or_none(target.get_model, fx["model"])
    mv = get_or_none(model.get_version, fx["model_version"]) if model else None
    present = {f.name for f in mv.list_files()} if mv else set()
    missing = [f for f in src_files if f.name not in present]
    log(f"    target : model {'exists' if model else 'to create'}, version {'exists' if mv else 'to create'}, "
        f"{len(missing)} file(s) to copy")
    ids = {"model_id": str(model.id), "model_version_id": str(mv.id)} if mv else {}
    if not apply:
        return ids

    model = model or target.create_model(fx["model"], description=f"CI copy of {src_model.name} (generated)")
    mv = mv or model.create_version(
        name=fx["model_version"], framework=src_mv.framework, type=src_mv.type, labels=src_mv.labels
    )
    files_dir = work / "model"
    files_dir.mkdir(parents=True, exist_ok=True)
    for f in missing:
        f.download(str(files_dir))
        mv.store(f.name, files_dir / f.filename)
        log(f"    stored {f.name}")
    return {"model_id": str(model.id), "model_version_id": str(mv.id)}


# --------------------------------------------------------------------------- main
def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--manifest", type=Path, default=REPO / "tests/fixtures.toml")
    ap.add_argument("--lock", type=Path, default=REPO / "tests/fixtures.lock.toml")
    ap.add_argument("--only", action="append", help="fnmatch pattern on the fixture name (repeatable)")
    ap.add_argument("--apply", action="store_true", help="really create things in the CI org (default: dry-run)")
    ap.add_argument("--yes", action="store_true", help="with --apply: skip the typed confirmation")
    ap.add_argument("--include-todo", action="store_true", help="also process fixtures flagged 'todo'")
    ap.add_argument("--max-videos", type=int, default=2)
    ap.add_argument("--source-token-env", default="PXL_API_TOKEN_PROD")
    ap.add_argument("--staging-token-env", default="PXL_API_TOKEN_STAGING")
    args = ap.parse_args()

    manifest = load_manifest(args.manifest)
    org = manifest["org"]
    fixtures = {
        k: v for k, v in manifest["fixtures"].items() if not args.only or any(fnmatch.fnmatch(k, p) for p in args.only)
    }
    skipped_todo = [k for k, v in fixtures.items() if "todo" in v and not args.include_todo]
    todo_fixtures = {k: v for k, v in fixtures.items() if k not in skipped_todo}
    log(f"manifest OK: {len(manifest['fixtures'])} fixtures, {len(fixtures)} selected, "
        f"{len(skipped_todo)} skipped (todo), {len(manifest.get('skipped', {}))} on hold")
    for k in skipped_todo:
        log(f"  - skip {k}: {fixtures[k]['todo']}")

    src_token, stg_token = os.environ.get(args.source_token_env), os.environ.get(args.staging_token_env)
    missing = [n for n, t in ((args.source_token_env, src_token), (args.staging_token_env, stg_token)) if not t]
    if missing:
        log(f"\nmanifest validated only; set {', '.join(missing)} to check the sources and targets")
        return 0 if not args.apply else 2

    if args.apply and not args.yes:
        answer = input(f"\nThis will CREATE data in '{org['name']}' on {org['host']}. Type '{org['name']}' to continue: ")
        if answer.strip() != org["name"]:
            log("aborted")
            return 1

    from picsellia import Client

    clients = {
        "source": Client(api_token=src_token, organization_name=org["source_org"], host=org["source_host"]),
        "models_source": Client(api_token=stg_token, organization_name=org["base_models_source_org"], host=org["host"]),
        "ci": Client(api_token=stg_token, organization_name=org["name"], host=org["host"]),
    }
    caches: dict = {"datasets": {}, "models": {}}
    lock = load_lock(args.lock)
    failures: list[str] = []
    log(f"\n{'APPLY' if args.apply else 'DRY-RUN'} on {org['name']} ({org['host']})\n")

    for key, fx in todo_fixtures.items():
        log(f"[{key}]")
        work = Path(tempfile.mkdtemp(prefix="ci-fixture-"))
        try:
            ids = provision_dataset(fx, org, clients, caches, args.apply, args.max_videos, work)
            if "model" in fx:
                ids |= provision_model(fx, clients, caches, args.apply, work)
            if args.apply and ids:
                lock["org"]["datalake_id"] = str(clients["ci"].get_datalake(name=org["datalake"]).id)
                lock["fixtures"][key] = ids
                write_lock(args.lock, lock)
        except Exception as e:  # noqa: BLE001 - one failing fixture must not stop the others
            failures.append(key)
            log(f"    FAILED {type(e).__name__}: {e}")
        finally:
            shutil.rmtree(work, ignore_errors=True)

    log(f"\n{len(todo_fixtures) - len(failures)} ok, {len(failures)} failed" + (f": {', '.join(failures)}" if failures else ""))
    if not args.apply:
        log("dry-run: nothing was created. Re-run with --apply to provision.")
    return 1 if failures else 0


if __name__ == "__main__":
    sys.exit(main())
